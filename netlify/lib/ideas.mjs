export const IDEAS = { "4-5": AGE_4_5, "6-7": AGE_6_7, "8+": AGE_8_PLUS };

// Picks an idea for this age that the phone hasn't had recently ("used" holds ids like "6-7:12"). Returns { id, text }.
export function pickIdea(ageKey, used) {
  const list = IDEAS[ageKey] || IDEAS["6-7"];
  const seen = new Set((Array.isArray(used) ? used : []).filter((u) => typeof u === "string"));
  let pool = list.map((text, i) => ({ id: `${ageKey}:${i}`, text })).filter((x) => !seen.has(x.id));
  if (!pool.length) pool = list.map((text, i) => ({ id: `${ageKey}:${i}`, text })); // every one has been used: start again
  return pool[Math.floor(Math.random() * pool.length)];
}
